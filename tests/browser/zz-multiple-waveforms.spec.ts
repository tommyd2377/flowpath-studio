import { expect, test } from '@playwright/test';
import { settingsSection } from './settings-navigation';

test('ordinary creator selects and edits independent waveforms and reaches the ten-waveform cap', async ({ page, context }) => {
  await context.route('**/*', route => ['localhost', '127.0.0.1'].includes(new URL(route.request().url()).hostname) ? route.continue() : route.abort());
  await page.goto('/account');
  await page.getByRole('button', { name: 'Use test owner B', exact: true }).click();
  await settingsSection(page, 'appearance');
  await page.getByLabel('Waveform name', { exact: true }).fill('Alpha multi');
  await settingsSection(page, 'instructions');
  await page.getByLabel('What should your voice know about itself?', { exact: true }).fill('Alpha independent instructions.');
  await page.getByRole('button', { name: 'Save draft', exact: true }).click();
  await expect(page.locator('.account-status')).toContainText('Saved.');
  const alpha = new URL(page.url()).searchParams.get('id')!;
  await page.getByRole('button', { name: 'New waveform', exact: true }).click();
  await expect(page.getByLabel('Waveform name', { exact: true })).toHaveValue('');
  await page.getByLabel('Waveform name', { exact: true }).fill('Beta multi');
  await page.getByLabel('Voice', { exact: true }).selectOption('meridian');
  await page.getByLabel('Color hex code', { exact: true }).fill('#e25555');
  await settingsSection(page, 'instructions');
  await page.getByLabel('What should your voice know about itself?', { exact: true }).fill('Beta independent instructions.');
  await settingsSection(page, 'plugins');
  await page.getByRole('button', { name: 'Install Text Box', exact: true }).click();
  await page.getByRole('button', { name: 'Save draft', exact: true }).click();
  await expect(page.locator('.account-status')).toContainText('Saved.');
  const beta = new URL(page.url()).searchParams.get('id')!;
  expect(beta).not.toBe(alpha);
  const selector = page.getByLabel(/Waveform ·/);
  await selector.selectOption(alpha);
  await expect(page.getByLabel('Waveform name', { exact: true })).toHaveValue('Alpha multi');
  await expect(page.getByLabel('What should your voice know about itself?', { exact: true })).toHaveValue('Alpha independent instructions.');
  await selector.selectOption(beta);
  await expect(page.getByLabel('Waveform name', { exact: true })).toHaveValue('Beta multi');
  await expect(page.getByLabel('Voice', { exact: true })).toHaveValue('meridian');
  await expect(page.getByLabel('Color hex code', { exact: true })).toHaveValue('#e25555');
  await page.getByLabel('Waveform name', { exact: true }).fill('Unsaved beta');
  await expect(selector).toBeDisabled();
  await page.getByRole('button', { name: 'Discard changes', exact: true }).click();
  await expect(selector).toBeEnabled();
  await settingsSection(page, 'plugins');
  await expect(page.getByRole('button', { name: 'Remove Text Box', exact: true })).toBeEnabled();
  await expect(page.getByRole('link', { name: 'Manage documents', exact: true })).toHaveAttribute('href', `/account/knowledge?id=${beta}`);
  await page.getByRole('link', { name: 'Manage documents', exact: true }).click();
  await page.getByLabel('Add a document', { exact: true }).setInputFiles({ name: 'beta-multi.txt', mimeType: 'text/plain', buffer: Buffer.from('Only Beta knows this synthetic passage.') });
  await page.getByRole('button', { name: 'Upload document', exact: true }).click();
  await expect(page.getByRole('checkbox', { name: 'Use in my waveform', exact: true })).toBeChecked({ timeout: 20_000 });
  const headers = { Origin: 'http://127.0.0.1:3225' };
  const alphaKnowledge = await (await page.request.get(`/api/knowledge?id=${alpha}`)).json();
  expect(alphaKnowledge.documents.some((d: { filename: string }) => d.filename === 'beta-multi.txt')).toBe(false);
  expect((await (await page.request.get(`/api/knowledge?id=${beta}`)).json()).documents[0].filename).toBe('beta-multi.txt');
  await page.getByRole('link', { name: '← Waveform settings', exact: true }).click();
  await expect(page.getByLabel('Waveform name', { exact: true })).toHaveValue('Beta multi');
  const list = (await (await page.request.get('/api/waveform')).json()).waveforms;
  for (let i = list.length; i < 10; i++) {
    const id = crypto.randomUUID(), candidate = { name: `Extra ${i}`, initialPrompt: 'A synthetic waveform.', textPanel: null };
    expect((await page.request.post(`/api/creation-review?id=${id}&create=1`, { headers, data: { candidate } })).ok()).toBe(true);
    expect((await page.request.post(`/api/waveform?id=${id}`, { headers, data: candidate })).ok()).toBe(true);
  }
  const id = crypto.randomUUID(), candidate = { name: 'Eleventh', initialPrompt: 'A synthetic waveform.', textPanel: null };
  await page.request.post(`/api/creation-review?id=${id}&create=1`, { headers, data: { candidate } });
  expect((await page.request.post(`/api/waveform?id=${id}`, { headers, data: candidate })).status()).toBe(409);
  await page.reload();
  await expect(page.getByRole('button', { name: 'New waveform', exact: true })).toBeDisabled();
  await expect(page.getByText('You’ve reached the 10-waveform limit.', { exact: false })).toBeVisible();
  await page.setViewportSize({ width: 320, height: 700 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
