import { test, expect } from '@playwright/test';
import { randomUUID } from 'node:crypto';

const origin = 'http://127.0.0.1:3225';
test('publisher reviews grouped prose, explicitly approves and browses full topic text', async ({ page, context }, testInfo) => {
  await context.route(/^https?:\/\//, route => new URL(route.request().url()).origin === origin ? route.continue() : route.abort());
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  const post = async (path: string, data: unknown) => {
    const response = await page.request.post(path, { headers: { Origin: origin }, data });
    const body = await response.json(); expect(response.ok(), JSON.stringify(body)).toBeTruthy(); return body;
  };
  let site = (await post('/api/sites', { name: 'Brochure review', slug: `brochure-${Date.now()}`, kind: 'general' })).site;
  const text = '# Visitor guide\n## Local history\nHarbor was founded beside the river.\n\nRead the entire history with this final detail.';
  const upload = await page.request.post(`/api/sites/${site.id}/files`, { headers: { Origin: origin, 'Content-Type': 'text/plain', 'X-File-Name': 'guide.txt', 'X-Site-Revision': String(site.revision) }, data: Buffer.from(text) });
  expect(upload.ok()).toBeTruthy(); const uploaded = await upload.json(); site = uploaded.site;
  await post(`/api/sites/${site.id}/knowledge`, { action: 'analyze', fileId: uploaded.fileId, revision: site.revision, requestId: randomUUID() });
  await page.goto('/');
  await page.getByRole('combobox', { name: 'Current site', exact: true }).selectOption(site.id);
  await page.getByRole('navigation', { name: 'Workspace' }).getByRole('button', { name: 'Knowledge', exact: true }).click();
  const review = page.getByRole('region', { name: 'Knowledge proposal', exact: true });
  await expect(review.getByRole('button', { name: 'Apply to draft', exact: true })).toBeDisabled();
  const approve = review.getByRole('button', { name: /Approve reviewed content/ });
  await expect(approve).toBeDisabled();
  await review.getByRole('region', { name: 'Content review' }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: testInfo.outputPath('content-review.png') });
  await review.getByRole('checkbox', { name: /I have reviewed this content/ }).check();
  await review.getByRole('checkbox', { name: /I have reviewed this content/ }).uncheck();
  await expect(approve).toBeDisabled();
  await review.getByRole('checkbox', { name: /I have reviewed this content/ }).check();
  await approve.click();
  await expect(review.getByRole('button', { name: 'Apply to draft', exact: true })).toBeEnabled();
  await review.getByRole('button', { name: 'Apply to draft', exact: true }).click();
  await expect(page.getByText(/1 items saved in your draft/)).toBeVisible();
  site = (await (await page.request.get(`/api/sites/${site.id}`)).json()).site;
  expect(site.published).toBeNull();
  await post(`/api/sites/${site.id}`, { action: 'publish', revision: site.revision });
  await page.goto(`/s/${site.slug}`);
  const website = page.getByRole('region', { name: 'Browse approved information' });
  await expect(website.getByText('Read the entire history with this final detail.', { exact: true })).toBeVisible();
  await expect(page.locator('[data-voice-dock]')).toHaveCSS('--opening-progress', '0');
  await expect(website).toHaveCSS('opacity', '1');
  await page.screenshot({ path: testInfo.outputPath('brochure-desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(website.getByText('Read the entire history with this final detail.', { exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('brochure-mobile.png'), fullPage: true });
  await website.getByRole('button', { name: 'Open Local history', exact: true }).click();
  const focus = page.getByRole('dialog', { name: 'Local history', exact: true });
  await expect(focus).toContainText('Read the entire history with this final detail.');
  await focus.getByRole('button', { name: 'Close detail', exact: true }).click();
  await expect(focus).not.toBeVisible();
  expect(errors).toEqual([]);
});
